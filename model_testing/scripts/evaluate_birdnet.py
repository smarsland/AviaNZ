#!/usr/bin/env python3
"""
Evaluate BirdNET on test datasets and compare with ground truth.

This script provides external model evaluation using BirdNET as a baseline.
NOTE: This script requires audio files in the test datasets, which are not
      generated by the standard data pipeline. It's a standalone utility
      for comparing BirdNET performance.

Usage:
    # Install BirdNET first:
    pip install birdnetlib

    # Run BirdNET evaluation on test sets:
    python scripts/evaluate_birdnet.py \
        /path/to/test_set1 /path/to/test_set2 \
        --output results/birdnet_eval
        
    Note: Test datasets must have audio/ subfolders with .wav files
"""

