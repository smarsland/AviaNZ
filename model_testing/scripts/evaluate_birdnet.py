    def run(self, test_folders):
        for test_folder in test_folders:
            # Use parent folder name (e.g. 'avianz_split') — same convention as evaluate_kaytoo.py
            p = Path(test_folder).resolve()
            dataset_name = p.parent.name
            self.evaluate_folder(test_folder, dataset_name)

        if len(self.results) > 0:
            # Write result.json so analyze_all_results.py picks this up
            result_json = {
                'name': self.output_folder.name,
                'type': 'pretrained',
                'model': 'birdnet',
                'seed': 0,
                'status': 'completed',
            }
            if len(self.results) >= 1:
                result_json['test1_name'] = self.results[0]['dataset_name']
                result_json['test1_acc'] = self.results[0]['accuracy']
                result_json['test1_acc_labelled'] = self.results[0].get('accuracy_labelled', float('nan'))
                result_json['test1_acc_background'] = self.results[0].get('accuracy_background', float('nan'))
            if len(self.results) >= 2:
                result_json['test2_name'] = self.results[1]['dataset_name']
                result_json['test2_acc'] = self.results[1]['accuracy']
                result_json['test2_acc_labelled'] = self.results[1].get('accuracy_labelled', float('nan'))
                result_json['test2_acc_background'] = self.results[1].get('accuracy_background', float('nan'))
            with open(self.output_folder / 'result.json', 'w') as f:
                json.dump(result_json, f, indent=2)
            print(f"\nSaved result.json to {self.output_folder / 'result.json'}")

            # Save per-split raw score CSVs including ground-truth columns
            # (true_CLASSNAME) so tune_thresholds.py can run locally.
            for result in self.results:
                raw_records = result.get('raw_score_records', [])
                if not raw_records:
                    continue
                split_name = result['dataset_name']
                csv_path = self.output_folder / f'predictions_{split_name}.csv'
                # Build column list from the union of all records (non-target species
                # may only appear in some records).
                _skip = {'filename', 'gt_codes', 'gt_classes', 'pred_codes', 'correct'}
                class_cols = sorted({c for rec in raw_records for c in rec if c not in _skip})
                # Fill any missing columns with 0 so every record is complete.
                for rec in raw_records:
                    for c in class_cols:
                        if c not in rec:
                            rec[c] = 0.0
                with open(csv_path, 'w', newline='') as f:
                    writer = csv.writer(f)
                    writer.writerow(['filename'] + class_cols + [f'true_{c}' for c in class_cols])
                    for rec in raw_records:
                        gt_set = set(rec.get('gt_classes', []))
                        writer.writerow(
                            [rec['filename']]
                            + [f"{rec.get(c, 0.0):.6f}" for c in class_cols]
                            + [int(c in gt_set) for c in class_cols]
                        )
                print(f"Saved {len(raw_records)} raw score rows → {csv_path.name}")

            self.generate_birdnet_species_report()

            for result in self.results:
                self.generate_confusion_matrix(result)

            if len(self.results) > 1:
                self.generate_dataset_comparison()

            self.generate_per_species_accuracy()
            self.save_results()
            self.generate_summary_report()

            print(f"\n{'='*60}")
            print(f"✓ BirdNET evaluation complete!")
            print(f"  Results saved to: {self.output_folder}")
            print(f"{'='*60}")


